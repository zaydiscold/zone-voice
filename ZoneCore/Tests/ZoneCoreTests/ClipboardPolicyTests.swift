import XCTest
@testable import ZoneCore

/// What clipboard history keeps and what it does not: decided first from what the clipboard says
/// about itself (nothing read), then from the text.
final class ClipboardPolicyTests: XCTestCase {
    // MARK: Before anything is read

    func testZonesOwnCopiesAreKnownByTheirType() {
        XCTAssertEqual(ClipboardPolicy.skipBeforeReading(types: ["public.utf8-plain-text", ClipboardPolicy.ownType], field: .ordinary, skipsSecrets: true), .own)
        XCTAssertNil(ClipboardPolicy.skipBeforeReading(types: [ClipboardPolicy.ownType], field: .ordinary))
    }

    func testMarkedCopiesAreKeptUnlessFilteringIsEnabled() {
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                     "com.agilebits.onepassword"] {
            XCTAssertNil(ClipboardPolicy.skipBeforeReading(types: [type], field: .ordinary))
            XCTAssertEqual(ClipboardPolicy.skipBeforeReading(types: ["public.utf8-plain-text", type], field: .ordinary, skipsSecrets: true), .concealed, type)
        }
    }

    func testAPasswordCodeOrCardFieldMeansTheCopyIsNotRead() {
        XCTAssertEqual(ClipboardPolicy.skipBeforeReading(types: ["public.utf8-plain-text"], field: .secret, skipsSecrets: true), .privateField)
        XCTAssertNil(ClipboardPolicy.skipBeforeReading(types: [], field: .secret))
    }

    func testAnOrdinaryCopyInAnOrdinaryOrSignInFieldPassesTheFirstLook() {
        XCTAssertNil(ClipboardPolicy.skipBeforeReading(types: ["public.utf8-plain-text", "public.url"], field: .ordinary))
        // A sign-in field holds the copy back (`ClipboardCapture`), it does not condemn it.
        XCTAssertNil(ClipboardPolicy.skipBeforeReading(types: ["public.utf8-plain-text"], field: .signIn))
    }

    // MARK: The text

    private func skip(_ text: String, secrets: Bool = true) -> ClipboardSkip? {
        ClipboardPolicy.skipAfterReading(text, skipsSecrets: secrets)
    }

    func testOrdinaryTextIsKept() {
        for text in ["Pick up the dry cleaning before 6", "milk, eggs, the good bread", "https://example.com/a/B9x?utm=1",
                     "zayd@zayd.wtf", "feature/clipboard-history-2026-11-20", "1Z999AA10123456784", "+1 (415) 555-0134",
                     "221B Baker Street", "v1.0.5", "/Users/zaydk/Desktop/Notes2026.md", "github.com/zaydiscold/Zone2",
                     "Meeting moved to 3pm, Room B12", "ok", "42", "123", "123456789", "2026-11-20", "café"] {
            XCTAssertNil(skip(text), text)
        }
    }

    func testFourToEightDigitsAreACode() {
        for code in ["1234", "481516", "00420042", " 481516\n"] { XCTAssertEqual(skip(code), .code, code) }
    }

    func testCardNumbersPassTheirOwnCheck() {
        XCTAssertEqual(skip("4242 4242 4242 4242"), .card)
        XCTAssertEqual(skip("4242-4242-4242-4242"), .card)
        XCTAssertEqual(skip("378282246310005"), .card, "15 digits, American Express")
        XCTAssertNil(skip("4242 4242 4242 4243"), "fails the check digit: a long number, not a card")
        XCTAssertNil(skip("1234567890123456"))
    }

    func testAccessKeysAndPrivateKeys() {
        XCTAssertEqual(skip("sk-proj-abcdefghijklmnopqrstuvwx"), .key)
        XCTAssertEqual(skip("ghp_abcdefghijklmnopqrstuvwxyz0123456789"), .key)
        XCTAssertEqual(skip("AKIAIOSFODNN7EXAMPLE"), .key)
        XCTAssertEqual(skip("eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.dozjgNryP4J3jVmNHl0w5N_XgL0n3I9PlFUP0THsR8U"), .key)
        XCTAssertEqual(skip("-----BEGIN OPENSSH PRIVATE KEY-----\nb3BlbnNzaC1rZXk\n-----END OPENSSH PRIVATE KEY-----"), .key)
        XCTAssertNil(skip("sk-8 is the skill number"), "a sentence that starts like a key")
    }

    func testPasswordShapedWords() {
        for password in ["dekvuz-9cofpa-Xyrmyv", "nXg8-pwTz.4hKq", "Summer2024!", "Tr0ub4dor&3", "aB3dEf9hIjKl"] {
            XCTAssertEqual(skip(password), .password, password)
        }
        XCTAssertNil(skip("password"), "no capital and no digit: a word")
        XCTAssertNil(skip("Summer 2024 was hot"), "has spaces: a sentence")
        XCTAssertNil(skip("Ab3"), "too short to be one")
    }

    func testWithTheSwitchOffOnlySizeAndEmptinessApply() {
        for text in ["481516", "4242 4242 4242 4242", "Summer2024!", "ghp_abcdefghijklmnopqrstuvwxyz0123456789"] {
            XCTAssertNil(skip(text, secrets: false), text)
        }
        XCTAssertEqual(skip("  \n ", secrets: false), .empty)
        XCTAssertEqual(skip(String(repeating: "a", count: ClipboardPolicy.maxBytes + 1), secrets: false), .tooLong)
        XCTAssertNil(skip(String(repeating: "a ", count: ClipboardPolicy.maxBytes / 2), secrets: false), "exactly the limit")
    }

    func testTheLimitIsCountedInBytes() {
        // Each character and its following space take four UTF-8 bytes.
        XCTAssertEqual(skip(String(repeating: "語 ", count: ClipboardPolicy.maxBytes / 4 + 1)), .tooLong)
    }

    // MARK: Links

    func testALinkIsTheWholeCopyAndOnTheWeb() {
        XCTAssertEqual(ClipboardPolicy.link(in: " https://example.com/a?b=1\n")?.host, "example.com")
        XCTAssertNil(ClipboardPolicy.link(in: "see https://example.com"))
        XCTAssertNil(ClipboardPolicy.link(in: "mailto:a@b.co"))
        XCTAssertNil(ClipboardPolicy.link(in: "example.com"))
        XCTAssertNotNil(ClipboardEntry(text: "http://a.co/x", savedAt: Date(), route: .keyboard).link)
    }
}
