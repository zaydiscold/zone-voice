#!/usr/bin/env python3
# by zayd/cold @ zayd.wtf
"""Builds the keyboard's emoji catalog from Unicode's emoji-test.txt.

    curl -sSfLo /tmp/emoji/emoji-test.txt https://unicode.org/Public/emoji/latest/emoji-test.txt
    python3 -I scripts/make-emoji-catalog.py /tmp/emoji/emoji-test.txt

Writes ZoneCore/Sources/ZoneCore/Resources/emoji.tsv, read by `EmojiCatalog`:

    @Smileys & People               a category, in Apple's order
    1.0<TAB>👋<TAB>1.0:👋🏻 ...       emoji version, the emoji, its five skin tones (light to dark)

Only fully-qualified emoji, grouped the way Apple's emoji keyboard groups them (Smileys &
Emotion and People & Body together, Activity before Travel). Skin tones are kept only when one
tone covers the whole sequence; mixed-tone pairs are left out. The keyboard hides any emoji newer
than the running iOS can draw, so the newest Unicode release can be bundled without blank boxes.
"""

import re
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "ZoneCore/Sources/ZoneCore/Resources/emoji.tsv"

# Unicode group -> Apple category. Component (bare skin tones and hair) is not typed alone.
CATEGORY = {
    "Smileys & Emotion": "Smileys & People",
    "People & Body": "Smileys & People",
    "Animals & Nature": "Animals & Nature",
    "Food & Drink": "Food & Drink",
    "Activities": "Activity",
    "Travel & Places": "Travel & Places",
    "Objects": "Objects",
    "Symbols": "Symbols",
    "Flags": "Flags",
}
ORDER = ["Smileys & People", "Animals & Nature", "Food & Drink", "Activity",
         "Travel & Places", "Objects", "Symbols", "Flags"]
TONES = [0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF]
LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E(\d+\.\d+)\s")


def main(source: Path) -> None:
    group = None
    bases = {name: [] for name in ORDER}  # category -> [(codepoints, version)]
    toned = []  # (codepoints, version, tone)
    for raw in source.read_text(encoding="utf-8").splitlines():
        if raw.startswith("# group:"):
            group = raw.split(":", 1)[1].strip()
            continue
        match = LINE.match(raw)
        if not match or group not in CATEGORY:
            continue
        points = tuple(int(p, 16) for p in match.group(1).split())
        version = match.group(2)
        tones = {p for p in points if p in TONES}
        if not tones:
            bases[CATEGORY[group]].append((points, version))
        elif len(tones) == 1:
            toned.append((points, version, tones.pop()))

    def key(points):
        return tuple(p for p in points if p not in TONES and p != 0xFE0F)

    variants = {}  # base key -> {tone: (codepoints, version)}
    for points, version, tone in toned:
        variants.setdefault(key(points), {})[tone] = (points, version)

    text = lambda points: "".join(chr(p) for p in points)
    lines = ["# Generated by scripts/make-emoji-catalog.py from Unicode emoji-test.txt. Do not edit."]
    header = re.search(r"^# Version: (\S+)", source.read_text(encoding="utf-8"), re.M)
    if header:
        lines.append(f"# Unicode emoji {header.group(1)}")
    count = 0
    for name in ORDER:
        lines.append(f"@{name}")
        for points, version in bases[name]:
            fields = [version, text(points)]
            tones = variants.get(key(points), {})
            if all(t in tones for t in TONES):
                fields.append(" ".join(f"{tones[t][1]}:{text(tones[t][0])}" for t in TONES))
            lines.append("\t".join(fields))
            count += 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{count} emoji in {len(ORDER)} categories -> {OUTPUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: make-emoji-catalog.py path/to/emoji-test.txt")
    main(Path(sys.argv[1]))
