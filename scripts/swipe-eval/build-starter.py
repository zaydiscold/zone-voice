#!/usr/bin/env python3
"""Writes ZoneCore's SwipeVocabulary.swift from starter-words.txt.

Each word's rank is its measured usage mapped onto en-words.txt's rank scale: the median list
rank of lowercase dictionary words at the same wordfreq Zipf frequency (wordfreq blends web,
news, subtitles, Twitter and Reddit). The rank is never worse than its dictionary rank, and it is
capped at CAP. Measured frequency undersells slang a person uses all the time, and the cap won on
the 2026-11-08 evaluation: same accuracy on 46,362 held-out human swipes as no boost, with
first-choice recall on everyday slang raised from 57% to 78% (docs/research/swipe-everyday-2026-11-08).

    python3 -m venv /tmp/wf && /tmp/wf/bin/pip install wordfreq
    /tmp/wf/bin/python -I scripts/swipe-eval/build-starter.py > ZoneCore/Sources/ZoneCore/Swipe/SwipeVocabulary.swift
"""
import collections
import statistics
from pathlib import Path

import wordfreq

CAP = 8000
PERSONAL = 1500  # the decoder's personal-word rank, for the names group (Neuralink)
ROOT = Path(__file__).resolve().parents[2]

ranks, blocked = {}, set()
buckets = collections.defaultdict(list)
for line in (ROOT / 'ZoneCore/Sources/ZoneCore/Resources/en-words.txt').read_text().splitlines():
    parts = line.split('\t')
    ranks[parts[0].lower()] = int(parts[1])
    if parts[0] == parts[0].lower() and len(parts) == 2:
        z = wordfreq.zipf_frequency(parts[0], 'en')
        if z > 0:
            buckets[round(z, 1)].append(int(parts[1]))
curve = {z: statistics.median(v) for z, v in buckets.items() if len(v) >= 15}


def rank(word, group):
    if group == 'names':
        return PERSONAL
    z = wordfreq.zipf_frequency(word, 'en')
    # Unseen by wordfreq (newer slang): no evidence, so the cap.
    measured = int(curve[min(curve, key=lambda c: abs(c - z))]) if z > 0 else CAP
    return min(ranks.get(word.lower(), measured), measured, CAP)


groups = []
for line in (Path(__file__).with_name('starter-words.txt')).read_text().splitlines():
    if line.strip() and not line.startswith('#'):
        name, *words = line.split()
        groups.append((name, list(dict.fromkeys(words))))

print('// by zayd/cold @ zayd.wtf')
print()
print('/// Everyday words that formal frequency lists underweight: texting slang and profanity.')
print('/// Swipe-only: they never become unsolicited tap')
print('/// autocorrections or saved personal words. Generated by scripts/swipe-eval/build-starter.py from')
print('/// starter-words.txt; each rank is measured usage on the word list\'s scale, capped at 8,000.')
print('public enum SwipeVocabulary {')
print('    public static let starter: [(word: String, rank: Int)] = [')
for name, words in groups:
    print(f'        // {name}')
    items = [f'("{w}", {rank(w, name)})' for w in words]
    line = '       '
    for item in items:
        if len(line) + len(item) + 2 > 110:
            print(line.rstrip())
            line = '       '
        line += ' ' + item + ','
    print(line.rstrip())
print('    ]')
print('}')
